const PATTERN_BY_ID = new Map(PATTERNS.map((p) => [p.id, p]));

export function getPatternById(id) {
  return PATTERN_BY_ID.get(id) || null;
}

export function getPatternsByCategory(categoryId) {
  return PATTERNS.filter((p) => p.category === categoryId);
}

// --- Legacy pattern text compatibility ------------------------------------
// Old records store a free-typed `patternIdentified` string (e.g.
// "Hashmap", "Two Pointer", "DP"). This builds a case-insensitive lookup
// from those known spellings to a canonical pattern id, so an old record
// CAN be shown with its proper canonical name and pre-selected on edit —
// without ever rewriting the stored text, and without guessing at anything
// that isn't an exact, safe match.
const LEGACY_LOOKUP = new Map();
for (const pattern of PATTERNS) {
  for (const legacyName of pattern.legacyNames || []) {
    LEGACY_LOOKUP.set(legacyName.toLowerCase().trim(), pattern.id);
  }
  LEGACY_LOOKUP.set(pattern.name.toLowerCase().trim(), pattern.id);
}

/** Maps an old free-text pattern string to a canonical pattern id, or null if unmappable. */
export function resolveLegacyPatternName(text) {
  if (!text || typeof text !== "string") return null;
  const key = text.toLowerCase().trim();
  if (!key || key === "-") return null;
  return LEGACY_LOOKUP.get(key) || null;
}

/**
 * Best-effort display name for a revision's pattern: prefers the canonical
 * primaryPattern slug, falls back to the legacy patternIdentified free text
 * (mapped to a canonical name when recognizable, shown as-is otherwise),
 * and never silently drops old data.
 */
export function resolvePatternDisplay(task) {
  if (task?.primaryPattern) {
    const canonical = getPatternById(task.primaryPattern);
    if (canonical) return { name: canonical.name, id: canonical.id, legacy: false };
    // primaryPattern holds something not in the current catalogue — show it
    // as-is rather than hiding it.
    return { name: task.primaryPattern, id: null, legacy: false };
  }
  const legacyText = task?.patternIdentified;
  if (legacyText && legacyText !== "-") {
    const mappedId = resolveLegacyPatternName(legacyText);
    if (mappedId) {
      const canonical = getPatternById(mappedId);
      return { name: canonical.name, id: canonical.id, legacy: true };
    }
    return { name: legacyText, id: null, legacy: true };
  }
  return null;
}
